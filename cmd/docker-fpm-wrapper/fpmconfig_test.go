// fakeFpmDump is a short "php-fpm -tt" dump with a pool that writes the slowlog and a pool
// that does not.
const fakeFpmDump = `[21-Oct-2026 20:14:43] NOTICE: [global]
[21-Oct-2026 20:14:43] NOTICE: 	error_log = /dev/null
[21-Oct-2026 20:14:43] NOTICE:
[21-Oct-2026 20:14:43] NOTICE: [www]
[21-Oct-2026 20:14:43] NOTICE: 	listen = 9000
[21-Oct-2026 20:14:43] NOTICE: 	slowlog = /var/log/www.slow
[21-Oct-2026 20:14:43] NOTICE: 	request_slowlog_timeout = 3s
[21-Oct-2026 20:14:43] NOTICE:
[21-Oct-2026 20:14:43] NOTICE: [api]
[21-Oct-2026 20:14:43] NOTICE: 	listen = 9001
[21-Oct-2026 20:14:43] NOTICE: 	slowlog = /var/log/api.slow
[21-Oct-2026 20:14:43] NOTICE: 	request_slowlog_timeout = 0s
[21-Oct-2026 20:14:43] NOTICE:
[21-Oct-2026 20:14:43] NOTICE: configuration file /tmp/php-fpm-test.conf test is successful
`

// writeFakeFpm writes a php-fpm script that keeps its arguments in a file and prints the dump.
// It also writes an empty php-fpm.conf to dir.
func writeFakeFpm(t *testing.T, dir, dump string) (fpmPath, argsPath string) {
	t.Helper()

	fpmPath = filepath.Join(dir, "php-fpm")
	argsPath = filepath.Join(dir, "args")
	require.NoError(t, os.WriteFile(filepath.Join(dir, "php-fpm.conf"), nil, 0o644))
	dumpPath := filepath.Join(dir, "dump")
	require.NoError(t, os.WriteFile(dumpPath, []byte(dump), 0o644))

	script := "#!/bin/sh\necho \"$*\" > '" + argsPath + "'\ncat '" + dumpPath + "' >&2\n"
	require.NoError(t, os.WriteFile(fpmPath, []byte(script), 0o755))

	return fpmPath, argsPath
}

func TestPrepareFpmConfig(t *testing.T) {
	tests := []struct {
		name          string
		proxyErrorLog bool
		proxySlowlog  bool
		wantOverlay   string // the text of the overlay after the include section; %s is the run dir
		wantErrorLog  string // %s is the run dir
		wantSlowlogs  []string
	}{
		{
			name:          "all proxies",
			proxyErrorLog: true,
			proxySlowlog:  true,
			wantOverlay:   "[global]\nerror_log = \"%s/error.log\"\n\n[www]\nslowlog = \"%s/slowlog-www.log\"\n",
			wantErrorLog:  "%s/error.log",
			wantSlowlogs:  []string{"%s/slowlog-www.log", ""},
		},
		{
			name:         "no error log proxy",
			proxySlowlog: true,
			wantOverlay:  "[www]\nslowlog = \"%s/slowlog-www.log\"\n",
			wantSlowlogs: []string{"%s/slowlog-www.log", ""},
		},
		{
			name:          "no slowlog proxy",
			proxyErrorLog: true,
			wantOverlay:   "[global]\nerror_log = \"%s/error.log\"\n",
			wantErrorLog:  "%s/error.log",
			wantSlowlogs:  []string{"", ""},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			runDir := filepath.Join(dir, "run")
			fpmPath, argsPath := writeFakeFpm(t, dir, fakeFpmDump)
			userConfig := filepath.Join(dir, "php-fpm.conf")
			inRunDir := func(s string) string { return strings.ReplaceAll(s, "%s", runDir) }

			setup, err := prepareFpmConfig(t.Context(), fpmPath, userConfig, []string{"-d", "a=b"},
				runDir, tt.proxyErrorLog, tt.proxySlowlog)
			require.NoError(t, err)

			args, err := os.ReadFile(argsPath)
			require.NoError(t, err)
			assert.Equal(t, "-d a=b --fpm-config "+runDir+"/php-fpm-test.conf -tt", strings.TrimSpace(string(args)))

			testOverlay, err := os.ReadFile(filepath.Join(runDir, "php-fpm-test.conf"))
			require.NoError(t, err)
			assert.Contains(t, string(testOverlay), "include = \""+userConfig+"\"\n")
			assert.Contains(t, string(testOverlay), "error_log = \"/dev/null\"\nlog_level = \"notice\"\n")

			assert.Equal(t, filepath.Join(runDir, "php-fpm.conf"), setup.configPath)
			overlay, err := os.ReadFile(setup.configPath)
			require.NoError(t, err)
			assert.Equal(t,
				"; Generated by docker-fpm-wrapper. Do not edit.\n\n[global]\ninclude = \""+userConfig+"\"\n\n"+inRunDir(tt.wantOverlay),
				string(overlay))

			assert.Equal(t, inRunDir(tt.wantErrorLog), setup.errorLogPath)

			slowlogs := make([]string, 0, len(setup.pools))
			for _, pool := range setup.pools {
				slowlogs = append(slowlogs, pool.SlowlogPath)
			}
			wantSlowlogs := make([]string, 0, len(tt.wantSlowlogs))
			for _, slowlog := range tt.wantSlowlogs {
				wantSlowlogs = append(wantSlowlogs, inRunDir(slowlog))
			}
			assert.Equal(t, wantSlowlogs, slowlogs)
		})
	}
}

func TestPrepareFpmConfig_Errors(t *testing.T) {
	t.Run("relative config path becomes absolute", func(t *testing.T) {
		dir := t.TempDir()
		fpmPath, _ := writeFakeFpm(t, dir, fakeFpmDump)
		t.Chdir(dir)

		setup, err := prepareFpmConfig(t.Context(), fpmPath, "php-fpm.conf", nil, filepath.Join(dir, "run"), true, true)
		require.NoError(t, err)

		overlay, err := os.ReadFile(setup.configPath)
		require.NoError(t, err)
		assert.Contains(t, string(overlay), "include = \""+filepath.Join(dir, "php-fpm.conf")+"\"")
	})

	t.Run("config does not exist", func(t *testing.T) {
		dir := t.TempDir()
		fpmPath, _ := writeFakeFpm(t, dir, fakeFpmDump)

		_, err := prepareFpmConfig(t.Context(), fpmPath, filepath.Join(dir, "missing.conf"), nil, filepath.Join(dir, "run"), true, true)
		assert.ErrorContains(t, err, "find php-fpm config")
	})

	t.Run("php-fpm rejects the config", func(t *testing.T) {
		dir := t.TempDir()
		fpmPath := filepath.Join(dir, "php-fpm")
		require.NoError(t, os.WriteFile(fpmPath, []byte("#!/bin/sh\necho 'ERROR: No pool defined' >&2\nexit 78\n"), 0o755))
		userConfig := filepath.Join(dir, "php-fpm.conf")
		require.NoError(t, os.WriteFile(userConfig, nil, 0o644))

		_, err := prepareFpmConfig(t.Context(), fpmPath, userConfig, nil, filepath.Join(dir, "run"), true, true)
		assert.ErrorContains(t, err, "run php-fpm -tt: exit status 78: ERROR: No pool defined")
	})

	t.Run("run dir cannot be created", func(t *testing.T) {
		dir := t.TempDir()
		fpmPath, _ := writeFakeFpm(t, dir, fakeFpmDump)
		file := filepath.Join(dir, "file")
		require.NoError(t, os.WriteFile(file, nil, 0o644))

		_, err := prepareFpmConfig(t.Context(), fpmPath, filepath.Join(dir, "php-fpm.conf"), nil, filepath.Join(file, "run"), true, true)
		assert.ErrorContains(t, err, "create run dir")
	})
}
