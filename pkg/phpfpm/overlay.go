package phpfpm

import (
	"bytes"
	"fmt"
	"maps"
	"os"
	"slices"
	"strings"
)

// Overlay is a php-fpm config that includes another config and then changes some directives of
// it. php-fpm applies the directives in order, so a directive of the overlay replaces the same
// directive of the included config. A pool section of the overlay adds to the pool with the same
// name.
type Overlay struct {
	Include string                       // the path of the included config
	Global  map[string]string            // the directives of [global]
	Pools   map[string]map[string]string // the directives of each pool, by the name of the pool
}

// overlayValueUnsafeChars are the characters that the php-fpm ini parser does not keep as they
// are in a double-quoted value.
const overlayValueUnsafeChars = "\"\r\n$\\"

func writeOverlaySection(buf *bytes.Buffer, name string, directives map[string]string) error {
	if len(directives) == 0 {
		return nil
	}

	_, _ = fmt.Fprintf(buf, "\n[%s]\n", name)
	for _, key := range slices.Sorted(maps.Keys(directives)) {
		value := directives[key]
		if strings.ContainsAny(value, overlayValueUnsafeChars) {
			return fmt.Errorf("value of %s in [%s] has a character from %q: %q", key, name, overlayValueUnsafeChars, value)
		}

		_, _ = fmt.Fprintf(buf, "%s = \"%s\"\n", key, value)
	}

	return nil
}

// Render returns the text of the overlay.
func (o Overlay) Render() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("; Generated by docker-fpm-wrapper. Do not edit.\n")

	if err := writeOverlaySection(&buf, "global", map[string]string{"include": o.Include}); err != nil {
		return nil, err
	}

	if err := writeOverlaySection(&buf, "global", o.Global); err != nil {
		return nil, err
	}

	for _, name := range slices.Sorted(maps.Keys(o.Pools)) {
		if err := writeOverlaySection(&buf, name, o.Pools[name]); err != nil {
			return nil, err
		}
	}

	return buf.Bytes(), nil
}

// WriteFile renders the overlay to the file at path.
func (o Overlay) WriteFile(path string) error {
	data, err := o.Render()
	if err != nil {
		return fmt.Errorf("render php-fpm config overlay: %w", err)
	}

	if err := os.WriteFile(path, data, 0o644); err != nil {
		return fmt.Errorf("write php-fpm config overlay: %w", err)
	}

	return nil
}
