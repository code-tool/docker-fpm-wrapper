package phpfpm

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestOverlay_Render(t *testing.T) {
	tests := []struct {
		name    string
		overlay Overlay
		want    string
		wantErr string
	}{
		{
			name: "include, global, and pools",
			overlay: Overlay{
				Include: "/etc/php/php-fpm.conf",
				Global:  map[string]string{"log_level": "notice", "error_log": "/dev/null"},
				Pools: map[string]map[string]string{
					"www": {"slowlog": "/tmp/docker-fpm-wrapper/slowlog-www.log"},
					"api": {"slowlog": "/tmp/docker-fpm-wrapper/slowlog-api.log"},
				},
			},
			want: `; Generated by docker-fpm-wrapper. Do not edit.

[global]
include = "/etc/php/php-fpm.conf"

[global]
error_log = "/dev/null"
log_level = "notice"

[api]
slowlog = "/tmp/docker-fpm-wrapper/slowlog-api.log"

[www]
slowlog = "/tmp/docker-fpm-wrapper/slowlog-www.log"
`,
		},
		{
			name:    "include only",
			overlay: Overlay{Include: "/etc/php/php-fpm.conf", Pools: map[string]map[string]string{"www": {}}},
			want:    "; Generated by docker-fpm-wrapper. Do not edit.\n\n[global]\ninclude = \"/etc/php/php-fpm.conf\"\n",
		},
		{
			name:    "value with a double quote",
			overlay: Overlay{Include: `/etc/php/"php-fpm".conf`},
			wantErr: `value of include in [global] has a character`,
		},
		{
			name:    "value with a variable",
			overlay: Overlay{Include: "/etc/php/php-fpm.conf", Pools: map[string]map[string]string{"www": {"slowlog": "/tmp/$pool.log"}}},
			wantErr: `value of slowlog in [www] has a character`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := tt.overlay.Render()
			if tt.wantErr != "" {
				assert.ErrorContains(t, err, tt.wantErr)
				return
			}

			require.NoError(t, err)
			assert.Equal(t, tt.want, string(got))
		})
	}
}

func TestOverlay_WriteFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "php-fpm.conf")
	require.NoError(t, Overlay{Include: "/etc/php/php-fpm.conf"}.WriteFile(path))

	data, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Contains(t, string(data), `include = "/etc/php/php-fpm.conf"`)

	t.Run("missing directory is an error", func(t *testing.T) {
		err := Overlay{Include: "/etc/php/php-fpm.conf"}.WriteFile(filepath.Join(t.TempDir(), "missing", "php-fpm.conf"))
		assert.ErrorContains(t, err, "write php-fpm config overlay")
	})
}
